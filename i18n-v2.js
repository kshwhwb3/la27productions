  const LANGS = ["es", "en", "de", "fr", "pt"];
  const STORAGE_KEY = "la27.lang";

  function getLang() {
    try {
      return localStorage.getItem(STORAGE_KEY);
    } catch (e) {
      return null;
    }
  }

  function setLang(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
  }

  function apply(lang) {
    const dict = T[lang];
    if (!dict) return;

    document.documentElement.lang = lang;

    // Text content
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      if (dict[k] != null) el.textContent = dict[k];
    });

    // HTML content (for elements with markup like <span class="it">)
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const k = el.getAttribute("data-i18n-html");
      if (dict[k] != null) el.innerHTML = dict[k];
    });

    // Re-stagger hero words after innerHTML rebuild
    const heroWords = document.querySelectorAll(".hero-title .word > span");
    heroWords.forEach((sp, i) => {
      sp.style.animationDelay = (0.1 + i * 0.08) + "s";
      // Trigger reflow so animation re-runs if already played
      sp.style.animation = "none";
      void sp.offsetWidth;
      sp.style.animation = "";
    });

    // Update lang switcher current
    const cur = document.querySelector(".lang-switch-current");
    if (cur) cur.textContent = dict["lang.code"];

    // Update active state on switcher
    document.querySelectorAll(".lang-switch-menu a, .lang-overlay-list a").forEach((a) => {
      a.classList.toggle("is-active", a.dataset.lang === lang);
    });
  }

  return { T, LANGS, getLang, setLang, apply };

